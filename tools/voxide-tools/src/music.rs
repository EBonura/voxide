//! Cook the music: `assets/music/tracks.txt` lists the pieces; this has
//! `psx-audio-cook xa-encode` interleave them into `MUSIC<n>.XA` files and
//! writes `game/src/musicdata.rs`.
//!
//! The pieces are rendered by `tools/loop-mixer` (a seeded sequence of loops
//! with crossfades), so each is a finished stretch of music: the game plays one
//! through and then waits, as Java does.
//!
//! The manifest is blocks of `key = value` lines:
//!
//! ```text
//! [credits]
//! line = MUSIC: SOMEONE            # a line of the credits card, at most 34 characters
//! [track]
//! name = Piece 1
//! file = piece-1.wav               # relative to --src
//! ```

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

/// Songs one interleaved file holds: 37.8 kHz stereo at single speed puts one
/// song in every fourth sector (psx-audio-cook docs/XA-MUSIC.md).
pub const STRIDE: usize = 4;

/// One manifest track.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Spec {
    /// Shown in the cooked table.
    pub name: String,
    /// WAV, relative to the source directory.
    pub file: String,
}

/// The parsed manifest.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Manifest {
    /// The tracks, in file order: four to a file, one per channel.
    pub tracks: Vec<Spec>,
    /// Lines of the credits card.
    pub credits: Vec<String>,
}

/// Longest credit line the credits card fits.
pub const CREDIT_COLUMNS: usize = 34;
/// Credit lines the credits card has room for.
pub const CREDIT_LINES: usize = 6;

/// Parse the manifest.
pub fn parse_manifest(text: &str) -> Result<Manifest, String> {
    let mut m = Manifest {
        tracks: Vec::new(),
        credits: Vec::new(),
    };
    let mut in_credits = false;
    for (n, raw) in text.lines().enumerate() {
        let line = raw.split('#').next().unwrap_or("").trim();
        if line.is_empty() {
            continue;
        }
        let at = |msg: &str| format!("tracks.txt line {}: {msg}", n + 1);
        if line == "[credits]" {
            in_credits = true;
            continue;
        }
        if line == "[track]" {
            in_credits = false;
            m.tracks.push(Spec {
                name: String::new(),
                file: String::new(),
            });
            continue;
        }
        let (key, value) = line
            .split_once('=')
            .ok_or_else(|| at("expected key = value"))?;
        let (key, value) = (key.trim(), value.trim());
        if in_credits {
            if key != "line" {
                return Err(at("[credits] takes `line = ...`"));
            }
            if value.len() > CREDIT_COLUMNS {
                return Err(at(&format!(
                    "a credit line is at most {CREDIT_COLUMNS} characters"
                )));
            }
            m.credits.push(value.to_string());
            continue;
        }
        let spec = m
            .tracks
            .last_mut()
            .ok_or_else(|| at("a key before any [track]"))?;
        match key {
            "name" => spec.name = value.to_string(),
            "file" => spec.file = value.to_string(),
            other => return Err(at(&format!("unknown key `{other}`"))),
        }
    }
    if m.tracks.is_empty()
        || m.tracks
            .iter()
            .any(|t| t.name.is_empty() || t.file.is_empty())
    {
        return Err("every [track] needs a name and a file".into());
    }
    if m.tracks.len() > STRIDE * 9 {
        return Err("more songs than nine files hold".into());
    }
    if m.credits.is_empty() || m.credits.len() > CREDIT_LINES {
        return Err(format!(
            "the credits card has room for 1 to {CREDIT_LINES} music lines"
        ));
    }
    Ok(m)
}

/// The `"seconds":` values of an `xa-encode` manifest, in song order.
pub fn manifest_seconds(json: &str) -> Vec<f64> {
    json.split("\"seconds\":")
        .skip(1)
        .filter_map(|t| {
            let end = t.find(|c: char| !(c.is_ascii_digit() || c == '.'))?;
            t[..end].parse().ok()
        })
        .collect()
}

/// One cooked song, as the game's table carries it.
#[derive(Debug, Clone, PartialEq)]
pub struct Cooked {
    /// Shown in the table.
    pub name: String,
    /// XA file number.
    pub file: u8,
    /// Channel in that file.
    pub channel: u8,
    /// Length the scheduler plays it for.
    pub length_ms: u32,
}

/// The generated `game/src/musicdata.rs`.
pub fn render_data(songs: &[Cooked], files: usize, credits: &[String]) -> String {
    let mut s = String::new();
    s.push_str(
        "//! GENERATED by tools/voxide-tools (convert-music) from assets/music/tracks.txt\n",
    );
    s.push_str(
        "//! -- do not edit by hand. The pieces on the disc and the credit lines the credits\n",
    );
    s.push_str("//! card shows.\n\n");
    s.push_str("/// One piece: the XA file number (and `MUSIC<file>.XA`), its channel in that\n");
    s.push_str("/// file and the length the scheduler plays it for.\n");
    s.push_str("pub struct Track {\n    #[allow(dead_code)] // the table\'s own documentation\n    pub name: &'static str,\n    pub file: u8,\n    pub channel: u8,\n    pub length_ms: u32,\n}\n\n");
    let _ = writeln!(
        s,
        "/// Song files on the disc.\npub const FILES: usize = {files};\n"
    );
    let _ = writeln!(s, "pub const TRACKS: [Track; {}] = [", songs.len());
    for c in songs {
        let _ = writeln!(
            s,
            "    Track {{ name: {:?}, file: {}, channel: {}, length_ms: {} }},",
            c.name, c.file, c.channel, c.length_ms
        );
    }
    s.push_str("];\n\n");
    let _ = writeln!(
        s,
        "/// Lines of the credits card.\npub const CREDITS: [&str; {}] = [",
        credits.len()
    );
    for c in credits {
        let _ = writeln!(s, "    {c:?},");
    }
    s.push_str("];\n");
    s
}

/// Where things are for one run.
pub struct Job {
    /// `assets/music/tracks.txt`.
    pub manifest: PathBuf,
    /// Directory the manifest's `file` names are relative to.
    pub src: PathBuf,
    /// A built `psx-audio-cook`.
    pub cook: PathBuf,
    /// Where `MUSIC<n>.XA` and `MUSIC<n>.json` go.
    pub out_dir: PathBuf,
    /// The generated Rust table.
    pub data: PathBuf,
}

/// Cook everything. Prints one line per song.
pub fn run(job: &Job) -> Result<(), String> {
    let text = std::fs::read_to_string(&job.manifest)
        .map_err(|e| format!("{}: {e}", job.manifest.display()))?;
    let manifest = parse_manifest(&text)?;
    std::fs::create_dir_all(&job.out_dir).map_err(|e| e.to_string())?;
    let files = manifest.tracks.len().div_ceil(STRIDE);
    let mut cooked = Vec::new();
    for (index, group) in manifest.tracks.chunks(STRIDE).enumerate() {
        let number = index + 1;
        let xa = job.out_dir.join(format!("MUSIC{number}.XA"));
        let json = job.out_dir.join(format!("MUSIC{number}.json"));
        let out = Command::new(&job.cook)
            .arg("xa-encode")
            .arg(&xa)
            .args(group.iter().map(|s| job.src.join(&s.file)))
            .args(["--file", &number.to_string(), "--manifest"])
            .arg(&json)
            .output()
            .map_err(|e| format!("{}: {e}", job.cook.display()))?;
        if !out.status.success() {
            return Err(format!(
                "xa-encode failed: {}",
                String::from_utf8_lossy(&out.stderr)
            ));
        }
        let seconds = manifest_seconds(&String::from_utf8_lossy(&out.stdout));
        if seconds.len() != group.len() {
            return Err("xa-encode manifest did not list every song".into());
        }
        for (channel, spec) in group.iter().enumerate() {
            let length_ms = (seconds[channel] * 1000.0).round() as u32;
            println!(
                "{}: MUSIC{number}.XA channel {channel}, {length_ms} ms",
                spec.name
            );
            cooked.push(Cooked {
                name: spec.name.clone(),
                file: number as u8,
                channel: channel as u8,
                length_ms,
            });
        }
    }
    std::fs::write(&job.data, render_data(&cooked, files, &manifest.credits))
        .map_err(|e| e.to_string())?;
    Ok(())
}

/// Resolve `--flag value` style arguments into a [`Job`].
pub fn job_from_args(root: &Path, args: &[String]) -> Result<Job, String> {
    let mut manifest = root.join("assets/music/tracks.txt");
    let mut out_dir = root.join("assets/music");
    let mut data = root.join("game/src/musicdata.rs");
    let (mut src, mut cook) = (None, None);
    let mut it = args.iter();
    while let Some(flag) = it.next() {
        let value = it.next().ok_or_else(|| format!("{flag} takes a value"))?;
        match flag.as_str() {
            "--manifest" => manifest = value.into(),
            "--src" => src = Some(PathBuf::from(value)),
            "--cook" => cook = Some(PathBuf::from(value)),
            "--out-dir" => out_dir = value.into(),
            "--data" => data = value.into(),
            other => return Err(format!("unknown flag {other}")),
        }
    }
    Ok(Job {
        manifest,
        src: src.ok_or("--src DIR (the directory holding the WAVs) is required")?,
        cook: cook.ok_or("--cook PATH (a built psx-audio-cook) is required")?,
        out_dir,
        data,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const MANIFEST: &str = "\
# pieces
[credits]
line = MUSIC: SOMEONE
line = CC BY 4.0
[track]
name = A
file = a.wav
[track]
name = B
file = b.wav
";

    #[test]
    fn manifest_parses_tracks_and_credits() {
        let m = parse_manifest(MANIFEST).unwrap();
        assert_eq!(m.tracks.len(), 2);
        assert_eq!(
            m.tracks[1],
            Spec {
                name: "B".into(),
                file: "b.wav".into()
            }
        );
        assert_eq!(m.credits, ["MUSIC: SOMEONE", "CC BY 4.0"]);
    }

    #[test]
    fn manifest_refuses_what_the_card_cannot_show() {
        let long = MANIFEST.replace("CC BY 4.0", &"X".repeat(CREDIT_COLUMNS + 1));
        assert!(parse_manifest(&long).is_err());
        assert!(parse_manifest("[track]\nname = A\nfile = a.wav").is_err()); // no credits
        assert!(parse_manifest("[credits]\nline = X\n[track]\nname = A").is_err()); // no file
        assert!(parse_manifest("[credits]\nline = X\n[track]\nbogus = 1").is_err());
    }

    #[test]
    fn manifest_seconds_reads_the_encoder_json() {
        let j = r#"{"songs":[{"name":"a","seconds":198.400},{"name":"b","seconds":12.5}]}"#;
        assert_eq!(manifest_seconds(j), vec![198.4, 12.5]);
    }

    #[test]
    fn data_lists_tracks_and_credits() {
        let cooked = vec![
            Cooked {
                name: "A".into(),
                file: 1,
                channel: 0,
                length_ms: 1000,
            },
            Cooked {
                name: "B".into(),
                file: 1,
                channel: 1,
                length_ms: 2000,
            },
        ];
        let text = render_data(&cooked, 1, &["MUSIC: SOMEONE".to_string()]);
        assert!(text.contains("pub const FILES: usize = 1;"));
        assert!(text.contains("Track { name: \"B\", file: 1, channel: 1, length_ms: 2000 },"));
        assert!(text.contains("pub const CREDITS: [&str; 1]"));
    }
}
